const { test, expect } = require('@playwright/test')
const { login, order, noOverflow } = require('./fixtures.cjs')

const ok = (route, data) => route.fulfill({ json: { code: 200, data } })

test('需求上传失败可重试，发送失败刷新后保留，切换账号清空', async ({page}) => {
  await login(page, 'customer')
  await page.goto('/#/intake')
  await page.locator('.extras summary').click()
  const title = page.getByPlaceholder('留空时显示需求首行')
  const contact = page.getByPlaceholder('方便团队联系你')
  const submit = page.locator('form button[type=submit]')
  await title.fill('有附件的需求')
  await contact.fill('账号 A 联系方式')
  await page.getByLabel('要改什么？').fill('保留这段说明')
  let attempts = 0
  await page.route('**/jiedan/media/upload', route => ++attempts === 1 ?
    route.fulfill({json:{code:500, msg:'上传中断'}}) : ok(route,{url:'/uploads/retried.mp3', ext:'mp3'}))
  await page.locator('.att-uploader input[multiple]').setInputFiles({
    name:'需求录音.mp3', mimeType:'audio/mpeg', buffer:Buffer.from('audio test')
  })
  await expect(submit).toBeDisabled()
  await page.getByRole('button', {name:'重试', exact:true}).click()
  await expect(page.locator('.att-uploader .file-row')).toContainText('需求录音.mp3')
  let submitted
  await page.route('**/jiedan/order/intake',route=>{
    submitted = route.request().postDataJSON()
    return route.fulfill({json:{code:503, msg:'暂时无法提交'}})
  })
  await submit.click()
  await expect(page.getByRole('alert').filter({hasText:'暂时无法提交'})).toBeVisible()
  expect(submitted.attachments.map(f=>f.name)).toEqual(['需求录音.mp3'])
  await page.reload()
  await expect(title).toHaveValue('有附件的需求')
  await expect(contact).toHaveValue('账号 A 联系方式')
  await expect(page.locator('.file-row')).toContainText('需求录音.mp3')
  await page.evaluate(()=>{
    localStorage.setItem('customerToken','second-customer')
    localStorage.setItem('customerAccount','another-customer')
  })
  await page.reload()
  await expect(title).toHaveValue('')
  await expect(contact).toHaveValue('')
  await expect(page.locator('.file-row')).toHaveCount(0)
})

test('补充说明按问题保存，慢传时切换仍归原问题，手机横屏能操作反馈弹窗', async ({page}) => {
  await page.setViewportSize({width:667,height:375})
  await login(page, 'customer')
  const bugs = [{id:11,content:'第一条'}, {id:12,content:'第二条'}]
  await page.route('**/jiedan/portal/orders/1',r=>ok(r,{...order, bugs}))
  await page.goto('/#/projects/1?tab=bugs')
  const issue = (name) => page.locator('.bug-item').filter({hasText:name})
  const first=issue('第一条'), second=issue('第二条')
  const edit = card=>card.getByRole('button',{name:'补充说明',exact:true}).click()
  await edit(first)
  await first.locator('textarea').fill('第一条的草稿')
  let finish
  const hold = new Promise(resolve=>{finish=resolve})
  await page.route('**/jiedan/media/upload',async r=>{await hold; await ok(r,{url:'/uploads/one.txt'})})
  await first.locator('input[multiple]').setInputFiles({name:'第一条.txt',mimeType:'text/plain',buffer:Buffer.from('一')})
  await expect(first.getByRole('button',{name:'提交补充'})).toBeDisabled()
  await edit(second)
  await second.locator('textarea').fill('第二条的草稿')
  finish()
  await edit(first)
  await expect(first.locator('textarea')).toHaveValue('第一条的草稿')
  await expect(first.locator('.file-row')).toContainText('第一条.txt')
  await page.reload()
  await edit(second)
  await expect(second.locator('textarea')).toHaveValue('第二条的草稿')
  await expect(second.locator('.file-row')).toHaveCount(0)
  await page.getByRole('button',{name:'反馈问题',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'反馈问题'})
  await dialog.locator('textarea').fill('准备提交的新问题')
  const send=dialog.getByRole('button',{name:'提交反馈'})
  await expect(send).toBeInViewport({ratio:1})
  await expect(async () => {
    const b=await page.locator('.el-dialog.customer-issue-dialog').boundingBox()
    expect(b.y).toBeGreaterThanOrEqual(-1)
    expect(b.y+b.height).toBeLessThanOrEqual(376)
  }).toPass({timeout:3000})
  await dialog.getByRole('button',{name:'取消'}).click()
  await page.reload()
  await page.getByRole('button',{name:'反馈问题',exact:true}).click()
  await expect(dialog.locator('textarea')).toHaveValue('准备提交的新问题')
  await noOverflow(page)
})

test('同分钟两次回复都显示红点，断线保留列表，回到网页立即更新',async({page})=>{
  await page.setViewportSize({width:320,height:640})
  await login(page,'customer')
  let message={id:41,type:'reply',content:'第一条',time:'2026-11-08 15:10'}
  const snapshot=()=>({...order,lastMessage:message,timeline:[message],messageCount:1})
  let offline=false
  await page.route('**/jiedan/portal/orders',r=>offline ? r.fulfill({json:{code:503,msg:'连接中断'}}) : ok(r,[snapshot()]))
  await page.route('**/jiedan/portal/orders/1',r=>ok(r,snapshot()))
  await page.goto('/#/customer/messages')
  const card=page.locator('.message-card')
  const dot=card.locator('.unread-dot')
  await expect(dot).toHaveCount(1)
  await card.click()
  await expect(page.getByRole('textbox',{name:'项目沟通消息'})).toBeVisible()
  await expect(page.locator('.detail-page .bubble').filter({hasText:'第一条'})).toBeVisible()
  await page.goto('/#/customer/messages')
  await expect(card).toContainText('第一条')
  await expect(dot).toHaveCount(0)
  offline=true
  await page.getByRole('button',{name:'刷新'}).click()
  await expect(page.getByText('连接中断')).toBeVisible()
  await expect(card).toContainText('第一条')
  offline=false
  message={...message,id:42,content:'第二条'}
  await page.evaluate(()=>window.dispatchEvent(new Event('online')))
  await expect(card).toContainText('第二条')
  await expect(dot).toHaveCount(1)
  await expect(page.getByText('连接中断')).toHaveCount(0)
  await noOverflow(page)
})

test('项目沟通能直接选择 PDF，预览名称并发给团队',async({page})=>{
  await login(page,'customer')
  await page.goto('/#/projects/1?tab=chat')
  await page.route('**/jiedan/media/upload',r=>ok(r,{url:'/uploads/requirements.pdf',ext:'pdf'}))
  let posted
  await page.route('**/jiedan/portal/message',r=>{
    posted=r.request().postDataJSON()
    return ok(r,{...order,timeline:[{id:71,type:'message',time:'2026-11-08 10:01',...posted}]})
  })
  const choose=page.waitForEvent('filechooser')
  await page.getByRole('button',{name:'添加图片、视频或文件'}).click()
  const picker=await choose
  expect(await picker.element().getAttribute('accept')).toBeNull()
  await picker.setFiles({name:'新需求.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.5\n')})
  await expect(page.locator('.composer .file-chip')).toContainText('新需求.pdf')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await expect(page.getByRole('link',{name:'新需求.pdf'})).toHaveAttribute('href','/uploads/requirements.pdf')
  expect(posted.attachments[0]).toMatchObject({name:'新需求.pdf',type:'file'})
})
