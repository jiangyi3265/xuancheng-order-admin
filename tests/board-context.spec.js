const { test, expect } = require('@playwright/test')
const { fixture, order } = require('./fixtures.cjs')
const ok = (route, data) => route.fulfill({ json:{ code:200, data } })

async function board(page, width, path = '/#/order') {
  await fixture(page)
  await page.setViewportSize({width,height:640})
  await page.addInitScript(() => {
    localStorage.setItem('token','fixture-boss')
    localStorage.setItem('xc.orderView','kanban')
  })
  const rows = Array.from({length:90}, (_, index) => ({
    ...order, id:index+1, orderNo:'XC-'+(index+1), title:'商店 '+(index+1), customer:'客户 '+(index+1),
    unread:index===3 ? [1] : [], actionBugCount:index===4 ? 1 : 0, contact:'', requirement:'',
    coverUrl:'/app-icon-192.png'
  }))
  await page.route('**/jiedan/order/list', r => ok(r,rows))
  await page.route(/\/jiedan\/order\/\d+$/, r => ok(r,rows[Number(new URL(r.request().url()).pathname.split('/').pop())-1]))
  await page.route('**/jiedan/order/read', r => ok(r,{id:r.request().postDataJSON().id,version:1}))
  await page.goto(path)
  return rows
}

for (const width of [375,1366]) {
  test('全屏看板组内查找与待跟进可组合，详情返回保留位置 · '+width, async ({page}) => {
    await board(page,width)
    await page.getByRole('button',{name:'展开进行中',exact:true}).click()
    const dialog=page.getByRole('dialog',{name:'全屏看板'})
    const results=dialog.locator('.focus-results')
    const search=dialog.getByRole('textbox',{name:'搜索本组项目'})
    const attention=dialog.getByRole('button',{name:/待跟进/})
    await expect(dialog.locator('.focus-card')).toHaveCount(90)
    await attention.click()
    await expect(dialog.locator('.focus-card')).toHaveCount(2)
    await search.fill('XC-5')
    await expect(dialog.locator('.focus-card')).toHaveCount(1)
    await expect(dialog.locator('.focus-open')).toContainText('商店 5')
    await search.fill('不存在的项目')
    await expect(dialog.getByText('当前没有需要跟进的项目')).toBeVisible()
    await dialog.getByRole('button',{name:'清除本组筛选'}).click()
    await expect(search).toHaveValue('')
    await expect(attention).toHaveAttribute('aria-pressed','false')
    await search.fill('商店')
    const target=dialog.locator('.focus-open').filter({has:page.getByText('商店 80',{exact:true})})
    await target.scrollIntoViewIfNeeded()
    const position=await results.evaluate(el=>el.scrollTop)
    expect(position).toBeGreaterThan(100)
    await target.click()
    await expect(page.locator('.workspace-head h2')).toHaveText('商店 80')
    await (width===375?page.getByRole('button',{name:'关闭项目详情'}):page.locator('.workspace-head .close-btn')).click()
    await expect(target).toBeInViewport()
    await expect(search).toHaveValue('商店')
    expect(Math.abs(await results.evaluate(el=>el.scrollTop)-position)).toBeLessThan(4)
    await dialog.getByRole('button',{name:'返回看板'}).click()
    await page.getByRole('button',{name:'展开待确认',exact:true}).click()
    await expect(search).toHaveValue('')
    await expect(dialog.getByRole('status')).toHaveText('0 个项目')
  })

  test('多选时点封面或金额只勾选项目，单选入口退出后恢复 · '+width,async({page})=>{
    await board(page,width)
    const card=page.locator('.kanban .card').first()
    await expect(card).toBeVisible()
    await page.getByRole('button',{name:width===375?'多选':'多选项目',exact:true}).click()
    const zone=card.locator(width===375?'.project-cover':'.amount')
    // Bring the touch point above the fixed mobile navigation bar.
    await zone.evaluate(el => el.scrollIntoView({block:'center',inline:'nearest'}))
    const box=await zone.boundingBox()
    await page.mouse.click(box.x+box.width/2,box.y+box.height/2)
    await expect(page.locator('.project-batch-bar')).toContainText('已选 1 项')
    await expect(card).toHaveClass(/batch-selected/)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button',{name:'退出多选'}).click()
    await expect(card).not.toHaveClass(/batch-selected/)
    const open=card.getByRole('button',{name:/打开项目/})
    await open.focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('.workspace-head h2')).toBeVisible()
  })
}


test('从带状态的链接进入后，清空筛选能跨详情返回，人数与搜索结果一致', async ({page}) => {
  await board(page,1366,'/#/order?status=pending')
  const status=page.locator('.qchip.on').first()
  await expect(status).toContainText('待确认')
  await page.getByRole('button',{name:'清空筛选'}).click()
  await expect(page).not.toHaveURL(/status=pending/)
  const field=page.getByPlaceholder('搜项目名 / 客户 / 联系方式 / 需求')
  await field.fill('XC-5')
  const owner=page.locator('.qchip').filter({hasText:'小陈'})
  await expect(owner.locator('b')).toHaveText('11')
  const card=page.locator('.kanban .card').filter({has:page.getByText('商店 5',{exact:true})})
  await card.getByRole('button',{name:'处理问题（1）'}).click()
  await expect(page.locator('.workspace-head h2')).toHaveText('商店 5')
  await page.locator('.workspace-head .close-btn').click()
  await expect(status).toContainText('全部')
  await expect(field).toHaveValue('XC-5')
  await owner.click()
  await expect(page.getByRole('dialog',{name:'全屏看板'}).getByRole('status')).toHaveText('11 个项目')
})

for (const width of [390, 1366]) {
  test('待确认独立计数，确认后计入全部和负责人名下 · ' + width, async ({page}) => {
    await fixture(page)
    await page.setViewportSize({width, height:760})
    await page.addInitScript(() => {
      localStorage.setItem('token', 'fixture-boss')
      if (!localStorage.getItem('xc.orderView')) localStorage.setItem('xc.orderView', 'kanban')
    })
    const rows = ['pending', 'doing', 'review', 'done'].map((status, i) =>
      ({...order, id:i+1, title:['尚待确认', '正式开发', '正式验收', '已经完成'][i], status, ownerId:i===3?1:2}))
    await page.route('**/jiedan/order/list', route => ok(route, rows))
    await page.goto('/#/order')
    const chip = label => page.locator('.qchip').filter({hasText:label})
    const count = (label, n) => expect(chip(label).locator('b')).toHaveText(String(n))
    const dialog = page.getByRole('dialog',{name:'全屏看板'})
    const leave = () => dialog.getByRole('button',{name:'返回看板'}).click()
    await count('全部',3)
    await count('待确认',1)
    if (width > 768) {
      await count('小陈',2)
      await chip('小陈').click()
      await expect(dialog.locator('.focus-card')).toHaveCount(2)
      await expect(dialog).not.toContainText('尚待确认')
      await leave()
    } else {
      await expect(page.locator('.board-kanban-counts button').first().locator('b')).toHaveText('3')
    }
    await chip('全部').click()
    await expect(dialog.locator('.focus-card')).toHaveCount(3)
    await expect(dialog).not.toContainText('尚待确认')
    await leave()
    await page.getByRole('button',{name:'展开待确认',exact:true}).click()
    await expect(dialog.locator('.focus-card')).toHaveCount(1)
    await expect(dialog).toContainText('尚待确认')
    await leave()
    await page.getByRole('button', {name:width > 768 ? '多选项目' : '多选', exact:true}).click()
    const pendingCard = page.locator('.kanban .card').filter({hasText:'尚待确认'})
    await pendingCard.click()
    await expect(page.locator('.project-batch-bar')).toContainText('已选 1 项')
    await count('全部',3)
    await count('待确认',1)
    await page.getByRole('button', {name:'退出多选'}).click()
    await page.locator('label').filter({has:page.getByRole('radio',{name:'列表'})}).click()
    const list=page.locator('.list-card')
    await expect(list).toContainText('正式开发')
    await expect(list).not.toContainText('尚待确认')
    await chip('待确认').click()
    await expect(list).toContainText('尚待确认')
    await expect(list).not.toContainText('正式开发')
    rows[0].status='doing'
    await page.reload()
    await count('全部',4)
    await count('待确认',0)
    if (width > 768) await count('小陈',3)
    await expect(list).toContainText('尚待确认')
  })
}
