const { test, expect } = require('@playwright/test')

test('工作台双账号交接闭环，退回、说明、验收、撤回以及提醒计数', async ({browser,request,baseURL}) => {
  test.setTimeout(260000)
  const apiBase = process.env.E2E_BASE
  if (!apiBase || new URL(apiBase).hostname !== '127.0.0.1' || !/^xc_e2e_\d+$/.test(process.env.E2E_DB)) throw Error('需要隔离测试库')
  const api = async (token,path,method='GET',data) => (await request.fetch(apiBase+path,{
    method,data,headers:token ? {Authorization:'Bearer '+token}:{}
  })).json()
  async function ok(...args) {const res=await api(...args);expect(res.code,res.msg).toBe(200);return res.data}
  async function login(username,password) {
    const res=await api(null,'/login','POST',{username,password});expect(res.code,res.msg).toBe(200);return res.token
  }
  const boss=await login('admin','admin123')
  const username='turn'+Date.now().toString().slice(-8)
  await ok(boss,'/jiedan/staff','POST',{userName:username,nickName:'小周',password:'TeamTurn123'})
  const staff=await login(username,'TeamTurn123')
  const member=await ok(staff,'/jiedan/staff/me')
  const sender=await ok(boss,'/jiedan/staff/me')
  const title='交接回合 '+username
  const order=await ok(boss,'/jiedan/order','POST',{title,ownerId:member.id})
  const path='/jiedan/order/'+order.id
  await ok(staff,path+'/accept','POST')
  // 接收后开工：待确认的项目员工只有「开始做」，开工后才会出现「提交验收」
  await ok(staff,'/jiedan/order/status','PUT',{id:order.id,status:'doing'})
  const contexts = []
  async function workbench(token, width) {
    const ctx = await browser.newContext({baseURL,timezoneId:"Asia/Shanghai",viewport:{width,height:width===390?844:900}})
    contexts.push(ctx)
    await ctx.addInitScript(t=>localStorage.setItem('token',t),token)
    const page = await ctx.newPage()
    await page.goto('/#/workbench')
    return page
  }
  const card = (p,kind) => p.locator('.handoff-card[data-order-id="'+order.id+'"][data-kind="'+kind+'"]')
  const button = (scope,name) => scope.getByRole('button',{name,exact:true})
  const notice = p => p.getByRole('region',{name:'需要我处理的问题'})
  async function expandWaiting(page) {
    const toggle = page.getByRole('button',{name:/等对方/}).first()
    if (await toggle.getAttribute('aria-expanded')!=='true') await toggle.click()
  }
  async function submit(page,kind,note,label='做完了') {
    const row = card(page,kind)
    await button(row,label).click()
    const field = page.getByRole('textbox',{name:/做了什么/})
    await expect(field).toBeVisible()
    if ((await page.viewportSize()).width===390) await expect(field).not.toBeFocused()
    if (note) await field.fill(note)
    await field.press('Enter')
    await expect(field).toBeHidden()
  }
  async function handBack(page,kind,note,label='退回') {
    await button(card(page,kind),label).click()
    const dialog = page.locator('.el-message-box:visible, .el-dialog:visible').last()
    await dialog.locator('textarea,input:not([type="hidden"])').first().fill(note)
    await button(dialog,label).click()
  }
  async function snapshot(page,name) {
    if (process.env.E2E_HANDOFF_SHOTS) {
      await page.screenshot({path:require('node:path').join(process.env.E2E_HANDOFF_SHOTS,name+'.png')})
    }
  }
  async function counts(page) {
    // The accessible section includes ordinary work (approvals, unanswered customers) as well as handoffs.
    const group = page.getByRole('region',{name:'轮到我',exact:true})
    const more = group.getByRole('button',{name:/还有 \d+ 条，展开/})
    if (await more.isVisible()) await more.click()
    const n = await group.getByRole('listitem').count()
    await expect(page.getByRole('button',{name:'待处理通知，'+n+' 条',exact:true})).toBeAttached()
    await expect.poll(async()=>Number((await page.title()).match(/^\((\d+)\)/)?.[1] || 0)).toBe(n)
    const side = page.locator('.el-menu-item').filter({hasText:'工作台'}).locator('.menu-badge sup')
    if (n) await expect(side).toHaveText(String(n))
    else await expect(side).toHaveCount(0)
  }
  try {
    const owner = await workbench(staff,390)
    const reviewer = await workbench(boss,1440)
    const mine = p=>p.getByRole('region',{name:'轮到我',exact:true})
    const confirm = (p,kind)=>button(card(p,kind),'通过').click()
    const due=new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Shanghai'}).format(new Date(Date.now()+86400000))
    await ok(boss,path+'/next','PUT',{content:'把首页初稿发给孙总确认',due})
    await expect(card(owner,'next')).toContainText('交代给你',{timeout:25000})
    await expect(card(owner,'next')).toContainText('明天')
    await expect(owner.getByText('把首页初稿发给孙总确认',{exact:true})).toHaveCount(1)
    await expect(notice(owner)).toHaveCount(0)
    await expect(reviewer.getByRole('button',{name:/等小周处理 1/})).toBeVisible({timeout:25000})
    await Promise.all([counts(owner),counts(reviewer)])
    await snapshot(owner,'01-手机-收到交代')
    await submit(owner,'next','已发给孙总，他说周五回复')
    await expect(card(reviewer,'nextReview')).toContainText('已发给孙总，他说周五回复',{timeout:25000})
    await expect(card(reviewer,'nextReview')).toContainText('小周 做完了')
    await expandWaiting(owner)
    await expect(card(owner,'nextReview')).toContainText('确认')
    await Promise.all([counts(owner),counts(reviewer)])
    await snapshot(reviewer,'02-电脑-审核提交说明')
    const first = (await ok(boss,path)).taskTurns.next
    expect(first.requesterId).toBe(sender.id)
    expect((await api(staff,path+'/task-review','POST',{kind:'next',decision:'confirm',version:(await ok(staff,path)).version})).code).toBe(403)
    await handBack(reviewer,'nextReview','请核对两档报价')
    await expect(card(owner,'next')).toContainText('请核对两档报价',{timeout:25000})
    await expect(mine(owner).getByRole('listitem').first()).toContainText('请核对两档报价')
    await snapshot(owner,'03-手机-看到退回原因')
    await Promise.all([counts(owner),counts(reviewer)])
    await submit(owner,'next','已核对两个报价')
    await expect(card(reviewer,'nextReview')).toContainText('第 2 次',{timeout:25000})
    await expect(card(reviewer,'nextReview')).toContainText('已核对两个报价')
    await expect(card(reviewer,'nextReview')).not.toContainText('他说周五回复')
    await confirm(reviewer,'nextReview')
    await expect(card(owner,'nextReview')).toHaveCount(0,{timeout:25000})
    await expect(owner.locator('.el-notification').filter({hasText:'通过了'})).toContainText('把首页初稿发给孙总确认',{timeout:25000})
    await Promise.all([counts(owner),counts(reviewer)])
    const withBug=await ok(boss,'/jiedan/order/bug','POST',{orderId:order.id,content:'手机按钮换行',needsAction:true})
    const bug=withBug.bugs.find(b=>b.content==='手机按钮换行')
    await expect(card(owner,'bug')).toContainText('手机按钮换行',{timeout:25000})
    await expect(mine(owner).getByRole('listitem').filter({hasText:'手机按钮换行'})).toHaveCount(1)
    await expect(notice(owner)).toHaveCount(0)
    await owner.goto('/#/order')
    await expect(notice(owner)).toContainText('交代给你')
    await expect(button(notice(owner),'做完了')).toBeVisible()
    await owner.goto('/#/workbench')
    await submit(owner,'bug','在手机上测过了')
    await expect(card(reviewer,'issueReview')).toContainText('在手机上测过了',{timeout:25000})
    await handBack(reviewer,'issueReview','请再看窄屏')
    await expect(card(owner,'bug')).toContainText('请再看窄屏',{timeout:25000})
    await submit(owner,'bug','窄屏已验证')
    await expect(card(reviewer,'issueReview')).toContainText('窄屏已验证',{timeout:25000})
    await confirm(reviewer,'issueReview')
    await expect.poll(async()=>(await ok(staff,path)).bugs.find(b=>b.id===bug.id).status).toBe('resolved')
    await Promise.all([counts(owner),counts(reviewer)])
    await ok(boss,path+'/handling','PUT',{handled:false,version:(await ok(boss,path)).version})
    await expect(card(owner,'manual')).toBeVisible({timeout:25000})
    await submit(owner,'manual','误提交')
    await expandWaiting(owner)
    await button(card(owner,'manualReview'),'撤回').click()
    await expect(card(owner,'manual')).toBeVisible()
    await submit(owner,'manual','检查已完成')
    await expect(card(reviewer,'manualReview')).toContainText('检查已完成',{timeout:25000})
    await confirm(reviewer,'manualReview')
    await expect.poll(async()=>(await ok(staff,path)).handled).toBe(true)
    await owner.goto('/#/order?id='+order.id)
    await button(owner.locator('.workspace-head'),'提交验收').click()
    const firstDelivery = owner.getByRole('dialog',{name:'提交验收',exact:true})
    await firstDelivery.getByRole('textbox').first().fill('首版交付')
    await button(firstDelivery,'提交验收').click()
    await expect(firstDelivery).toBeHidden()
    await owner.goto('/#/workbench')
    await expect(card(reviewer,'deliveryReview')).toContainText('首版交付',{timeout:25000})
    await expect(mine(reviewer).getByRole('listitem').filter({hasText:title})).toHaveCount(1)
    await Promise.all([counts(owner),counts(reviewer)])
    await snapshot(reviewer,'04-电脑-整项目验收')
    await handBack(reviewer,'deliveryReview','预约表单提交后没有提示','退回返工')
    await expect(card(owner,'delivery')).toContainText('预约表单提交后没有提示',{timeout:25000})
    await snapshot(owner,'05-手机-项目退回返工')
    await Promise.all([counts(owner),counts(reviewer)])
    await button(card(owner,'delivery'),'改好了，再提交验收').click()
    const delivery = owner.getByRole('dialog',{name:'提交验收',exact:true})
    await delivery.getByRole('textbox').first().fill('已补提交成功提示')
    await button(delivery,'提交验收').click()
    await expect(card(reviewer,'deliveryReview')).toContainText('已补提交成功提示',{timeout:25000})
    await button(card(reviewer,'deliveryReview'),'验收通过').click()
    await button(reviewer.getByRole('dialog',{name:'项目验收',exact:true}),'验收通过').click()
    await expect.poll(async()=>(await ok(boss,path)).status).toBe('done')
    await expect(card(owner,'delivery')).toHaveCount(0)
    await expect(card(reviewer,'deliveryReview')).toHaveCount(0)
    await Promise.all([counts(owner),counts(reviewer)])
  } finally {
    for (const ctx of contexts) await ctx.close()
    await ok(boss,path,'DELETE')
  }
})
