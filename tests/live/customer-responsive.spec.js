const { test, expect } = require('@playwright/test')

for (const width of [1440, 1024, 390]) {
  test('客户从原入口提交需求并查看项目 '+width, async ({page}) => {
    await page.setViewportSize({width, height:900})
    await page.goto('/client/#/intake')
    await page.getByPlaceholder('请输入登录账号').fill('cust_a')
    await page.getByPlaceholder('请输入密码',{exact:true}).fill('customer123')
    await page.getByRole('button',{name:'登录',exact:true}).click()
    await expect(page).toHaveURL(/#\/intake$/)
    const nav=page.getByRole('navigation',{name:'客户导航'})
    await expect(nav.getByRole('link',{name:'提交需求'})).toHaveAttribute('aria-current','page')
    if (width>768) {
      await expect(page.locator('.portal-brand')).toBeVisible()
      const sidebar=await nav.boundingBox()
      const form=await page.locator('form.request-panel').boundingBox()
      expect(sidebar.x+sidebar.width).toBeLessThan(form.x)
    } else {
      expect((await nav.boundingBox()).y).toBeGreaterThan(780)
      await expect(page.locator('.portal-brand')).toHaveCount(0)
    }
    const title='双端需求-'+width+'-'+Date.now()
    await page.getByRole('button',{name:'用模板填写'}).click()
    await page.getByRole('button',{name:/图片替换/}).click()
    const description=page.getByLabel('要改什么？')
    await expect(description).toHaveValue(/图片位置/)
    await page.locator('.extras summary').click()
    await page.getByPlaceholder('留空时显示需求首行').fill(title)
    await description.fill('请更新一张首页参考图')
    await page.getByPlaceholder('方便团队联系你').fill('test-contact')
    await page.locator('.request-panel input[type=file]').setInputFiles({
      name:'reference.txt',mimeType:'text/plain',buffer:Buffer.from('需求附件测试')
    })
    await expect(page.locator('.request-panel .file-row')).toContainText('reference.txt')
    await page.setViewportSize({width:width===390?1280:375,height:900})
    await expect(description).toHaveValue('请更新一张首页参考图')
    await expect(page.locator('.request-panel .file-row')).toHaveCount(1)
    await page.setViewportSize({width,height:900})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
    await page.reload()
    await expect(description).toHaveValue('请更新一张首页参考图')
    await expect(page.locator('.request-panel .file-row')).toContainText('reference.txt')
    const result=page.waitForResponse(r=>r.url().endsWith('/jiedan/order/intake')&&r.request().method()==='POST')
    await page.getByRole('button',{name:'提交需求',exact:true}).click()
    expect((await (await result).json()).code).toBe(200)
    await expect(page.getByRole('heading',{name:'提交成功'})).toBeVisible()
    const created=(await (await result).json()).data
    await page.getByRole('button',{name:'查看处理进度'}).click()
    await expect(page).toHaveURL(new RegExp('/projects/' + created.id + '.*issue='+created.bugId))
    await expect(page.locator('#requirement-'+created.bugId)).toContainText(title)
    await page.goto('/#/intake')
    await expect(description).toHaveValue('')
    await expect(page.getByPlaceholder('方便团队联系你')).toHaveValue('')
    await expect(page.locator('.request-panel .file-row')).toHaveCount(0)
    await nav.getByRole('link',{name:'我的需求',exact:true}).click()
    const card=page.locator('.request-row').filter({hasText:title})
    await expect(card).toHaveCount(1)
    await card.click()
    await expect(page.locator('#requirement-'+created.bugId)).toContainText(title)
    await expect(page.locator('.detail-page')).toContainText('请更新一张首页参考图')
    if(width>768){
      await nav.getByRole('link',{name:'消息'}).click()
      await expect(page.getByRole('heading',{name:'消息中心'})).toBeVisible()
      await nav.getByRole('link',{name:'我的',exact:true}).click()
      await page.getByRole('button',{name:'账号与安全'}).click()
      await expect(page.getByRole('heading',{name:'账号安全'})).toBeVisible()
    } else {
      await expect(nav).toHaveCount(0)
    }
  })
}
