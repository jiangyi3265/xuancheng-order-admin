const { test, expect } = require('@playwright/test')

for (const width of [1440, 390]) {
  test('看板加急、截止时间与负责人提醒 ' + width, async ({ page }) => {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await page.goto('/#/login')
    await page.getByPlaceholder('请输入登录账号').fill('admin')
    await page.getByPlaceholder('请输入密码', {exact:true}).fill('admin123')
    await page.getByRole('button', {name:'登录', exact:true}).click()
    await expect(page).not.toHaveURL(/#\/login$/)
    const token = await page.evaluate(() => localStorage.getItem('token'))
    const api = async (path, method = 'GET', data) => {
      const res = await page.request.fetch(path, { method, data, headers:{ Authorization:'Bearer ' + token } })
      const json = await res.json()
      expect(json.code, json.msg).toBe(200)
      return json.data
    }
    const staff = (await api('/jiedan/staff/list')).find(m => m.role === 'employee')
    expect(staff).toBeTruthy()
    const title = '看板加急测试-' + width + '-' + Date.now()
    const order = await api('/jiedan/order', 'POST', { title, ownerId:staff.id, status:'doing', deadline:'2030-06-30' })
    const path = '/jiedan/order/' + order.id
    try {
      await page.evaluate(() => localStorage.setItem('xc.orderView', 'kanban'))
      await page.goto('/#/order')
      await page.reload()
      const card = page.locator('.kanban .card').filter({hasText:title})
      const trigger = card.locator('.urgency-trigger')
      const dialog = page.getByRole('dialog', {name:'加急截止时间'})
      await trigger.click()
      const cell = n => dialog.locator('.el-date-table td.available').filter({hasText:new RegExp('^' + n + '$')})
      await cell(15).click()
      const time = dialog.getByLabel('截止时间（北京时间）')
      await expect(time).toHaveValue('23:59')
      await time.fill('16:35')
      await dialog.getByRole('button', {name:'保存', exact:true}).click()
      await expect(trigger).toContainText(/-15 16:35/)
      const reminder = card.getByRole('button', {name:'提醒' + staff.nickName, exact:true})
      await reminder.click()
      await expect.poll(async () => (await api(path)).timeline.some(t => t.content.includes('16:35'))).toBe(true)
      await page.reload()
      await expect(trigger).toContainText(/-15 16:35/)
      await page.getByRole('button', {name:/^加急\s*\d+$/}).click()
      const group = page.getByRole('dialog', {name:'全屏看板'})
      const expanded = group.locator('.focus-card').filter({hasText:title})
      await expect(expanded.locator('.urgency-trigger')).toContainText('16:35')
      await expanded.getByRole('button', {name:'标为已处理'}).click()
      await expect(expanded.getByRole('button', {name:'改为未处理'})).toBeVisible()
      await expect(expanded.getByRole('button', {name:/^提醒/})).toHaveCount(0)
      await group.getByRole('button', {name:'返回看板'}).click()
      await card.getByRole('button', {name:'打开项目：' + title, exact:true}).click()
      const detail = page.locator('.workspace-head .urgency-trigger')
      await expect(detail).toContainText('16:35')
      await detail.click()
      await cell(17).click()
      await time.fill('09:10')
      await dialog.getByRole('button', {name:'返回', exact:true}).click()
      await page.getByRole('button', {name:'放弃', exact:true}).click()
      await expect(detail).toContainText('-15 16:35')
      await detail.click()
      await cell(17).click()
      await time.fill('09:10')
      await dialog.getByText(/将项目改为未处理/).click()
      await expect(dialog.getByRole('checkbox', {name:/将项目改为未处理/})).toBeChecked()
      await dialog.getByRole('button', {name:'保存', exact:true}).click()
      await expect(detail).toContainText('-17 09:10')
      const latest = await api(path)
      expect(latest.handled).toBe(false)
      expect(latest.deadline).toBe('2030-06-30')
      await detail.click()
      await dialog.getByRole('button', {name:'取消加急', exact:true}).click()
      await expect(detail).toHaveText('加急')
      await expect.poll(async () => (await api(path)).urgentUntil || null).toBe(null)
    } finally {
      await api(path, 'DELETE')
    }
  })
}
