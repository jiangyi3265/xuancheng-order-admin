const { test, expect } = require('@playwright/test')
const { fixture, order, members } = require('./fixtures.cjs')
const ok = (r, data) => r.fulfill({ json: { code: 200, data } })

async function setup(page) {
  await fixture(page)
  await page.addInitScript(() => {
    localStorage.setItem('token', 'fixture-boss')
    localStorage.setItem('xc.orderView', 'list')
  })
}

test('极速建单点背景不关闭，Esc、手机返回和刷新后恢复草稿，成功才清空', async ({page}) => {
  await setup(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/#/order')
  await expect(page.locator('.el-table__row').first()).toBeVisible()
  await page.keyboard.press('Alt+n')
  const dialog = page.locator('.design-quick-dialog')
  const text = dialog.locator('textarea')
  await text.fill('一套新的菜单，预算5000')
  await page.mouse.click(8, 360)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await page.keyboard.press('Alt+n')
  await expect(text).toHaveValue('一套新的菜单，预算5000')
  await expect(dialog.getByText('已恢复上次没建完的内容')).toBeVisible()
  await page.reload()
  await expect(text).toHaveValue('一套新的菜单，预算5000')
  await page.goto('/#/order')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button',{name:'极速建单',exact:true}).click()
  await page.goBack()
  await expect(dialog).toBeHidden()
  await expect(page).toHaveURL(/#\/order$/)
  await page.getByRole('button',{name:'极速建单',exact:true}).click()
  let fail = true
  await page.route('**/jiedan/order', r => fail ? r.fulfill({json:{code:500,msg:'失败'}}) : ok(r,{...order,id:5}))
  await dialog.getByRole('button',{name:'建单并派单'}).click()
  await expect(text).toHaveValue('一套新的菜单，预算5000')
  fail = false
  await dialog.getByRole('button',{name:'建单并派单'}).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button',{name:'极速建单',exact:true}).click()
  await expect(text).toHaveValue('')
  await expect(dialog.getByText('已恢复上次没建完的内容')).toHaveCount(0)
})

test('完整建单草稿跨菜单恢复、可清空，编辑项目不会覆盖建单草稿', async ({page}) => {
  await setup(page)
  await page.goto('/#/order')
  const dialog = page.locator('.design-order-dialog')
  const newButton = page.getByRole('button',{name:'新建项目',exact:true})
  await newButton.click()
  await dialog.locator('textarea').fill('要保留的完整需求')
  await page.goBack()
  await expect(dialog).toBeHidden()
  await page.goto('/#/workbench')
  await newButton.click()
  await expect(dialog.locator('textarea')).toHaveValue('要保留的完整需求')
  await dialog.getByRole('button',{name:'清空',exact:true}).click()
  await expect(dialog.locator('textarea')).toHaveValue('')
  await dialog.getByPlaceholder(/一句话写清/).fill('再次暂存')
  await page.goBack()
  await page.goto('/#/order?id=1')
  await page.locator('.head-actions-m').getByRole('button',{name:'编辑',exact:true}).click()
  await dialog.getByPlaceholder(/一句话写清/).fill('不保存的修改')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'继续填'}).click()
  await expect(page.getByRole('dialog',{name:'放弃修改'})).toBeHidden()
  await expect(dialog.getByPlaceholder(/一句话写清/)).toHaveValue('不保存的修改')
  await page.goBack()
  await page.getByRole('button',{name:'放弃',exact:true}).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('.workspace')).toBeVisible()
  await page.getByRole('button',{name:'关闭项目详情'}).click()
  await newButton.click()
  await expect(dialog.getByPlaceholder(/一句话写清/)).toHaveValue('再次暂存')
})

