test('从手机列表进入详情有骨架，浏览器返回保持列表位置', async ({page}) => {
  await setup(page)
  const rows = Array.from({length:24},(_,i)=>({...order,id:i+1,title:'独立项目'+(i+1),unread:[]}))
  await page.route('**/jiedan/order/list',r=>ok(r, rows))
  let waiting
  await page.route(/\/jiedan\/order\/\d+$/, r=>{ waiting=r })
  await page.goto('/#/order')
  const card = page.locator('.mobile-project-entry').nth(12)
  await card.scrollIntoViewIfNeeded()
  const top = await page.locator('.main').evaluate(e=>e.scrollTop)
  expect(top).toBeGreaterThan(250)
  await card.locator('.board-project-copy h3').click()
  await expect(page).toHaveURL(/id=\d+/)
  await expect(page.getByRole('status',{name:'正在加载项目详情'})).toBeVisible()
  const id = Number(new URLSearchParams(page.url().split('?')[1]).get('id'))
  await ok(waiting, rows.find(o=>o.id===id))
  await expect(page.locator('.project-skeleton')).toBeHidden()
  await page.goBack()
  await expect(page.locator('.workspace')).toBeHidden()
  await expect.poll(()=>page.locator('.main').evaluate(e=>e.scrollTop)).toBeCloseTo(top, -1)
})

test('工作台直达和详情翻页，输入框快捷键不误触，到边界按钮变灰', async ({page}) => {
  await setup(page)
  await page.setViewportSize({width:1300,height:800})
  await page.route('**/jiedan/order/list', r=>ok(r,[1,2,3].map(id=>({...order,id,title:'测试项目'+id,unread:[]}))))
  await page.route('**/jiedan/order/*', async r => {
    const id = Number(r.request().url().split('/').pop())
    if (id) await ok(r,{...order,id,title:'测试项目'+id})
    else await r.fallback()
  })
  await page.goto('/#/workbench?id=1&tab=chat')
  await expect(page.locator('.workspace-head h2')).toHaveText('测试项目1')
  await expect(page.getByRole('button',{name:'沟通',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.reload()
  await expect(page.locator('.workspace-head h2')).toHaveText('测试项目1')
  await page.goto('/#/order')
  await page.locator('.el-table__row').first().getByRole('cell').first().click()
  await expect(page).toHaveURL(/id=\d+/)
  const first = page.url()
  await expect(page.getByRole('button',{name:'上一个项目'})).toBeDisabled()
  const input = page.getByRole('textbox',{name:'回复客户'})
  await input.focus()
  await input.press('Alt+ArrowRight')
  expect(page.url()).toBe(first)
  await page.getByRole('button',{name:'下一个项目'}).click()
  await expect(page).not.toHaveURL(first)
  await page.keyboard.press('Alt+ArrowLeft')
  await expect(page).toHaveURL(first)
})

test('手机验收的底栏只占一行，关闭已填的退回原因可选择继续填', async ({page}) => {
  await setup(page)
  await page.setViewportSize({width:375,height:640})
  await page.route('**/jiedan/order/2', r=>ok(r,{...order,id:2,status:'review'}))
  await page.goto('/#/order?id=2')
  const bar = page.locator('.head-actions-m')
  const buttons = bar.getByRole('button')
  await expect(buttons).toHaveCount(3)
  const tops = await buttons.evaluateAll(items => items.map(el => Math.round(el.getBoundingClientRect().top)))
  expect(Math.max(...tops) - Math.min(...tops)).toBeLessThan(5)
  await bar.getByRole('button',{name:'退回返工'}).click()
  const form = page.locator('.design-reason-dialog')
  await form.locator('textarea').fill('请调整间距')
  await page.goBack()
  await page.getByRole('button',{name:'继续填'}).click()
  await expect(form.locator('textarea')).toHaveValue('请调整间距')
  await expect(page.getByRole('dialog',{name:'放弃修改'})).toBeHidden()
  await page.goBack()
  await page.getByRole('button',{name:'放弃',exact:true}).click()
  await expect(form).toBeHidden()
  await expect(page).toHaveURL(/#\/order\?id=2$/)
})
