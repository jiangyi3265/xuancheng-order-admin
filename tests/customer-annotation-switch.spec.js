const {expect, test} = require('@playwright/test')
const {fixture, order} = require('./fixtures.cjs')
const {editor, draw, screenshotFile} = require('./annotation-fixture.cjs')

test('保存圈注时切换需求，结果只写回原需求中的那张截图', async ({page}) => {
  await fixture(page, 'customer')
  await page.addInitScript(() => localStorage.setItem('customerToken', 'fixture-customer'))
  const bugs = [61, 62].map(id => ({id, status:'open', content:'需求 '+id, attachments:[], updates:[]}))
  await page.route('**/jiedan/portal/orders/1', r => r.fulfill({json:{code:200, data:{...order, bugs}}}))
  const reply = (route, url) => route.fulfill({json:{code:200, data:{url, ext:'png'}}})
  let pendingSave
  await page.route('**/jiedan/media/upload', async route => {
    const request = route.request()
    const body = new Response(request.postDataBuffer(), {headers:{'Content-Type':request.headers()['content-type']}})
    const file = (await body.formData()).get('file')
    if (file.name === '原截图.png') return reply(route, '/app-icon-192.png')
    pendingSave = route
  })
  await page.goto('/#/projects/1?tab=bugs&issue=61')
  const composer = page.locator('.issue-composer')
  const send = composer.getByRole('button', {name:'发送', exact:true})
  await composer.getByRole('textbox').fill('第一条的补充')
  await composer.locator('input[type=file]').first().setInputFiles(await screenshotFile(page, '原截图.png'))
  await composer.getByRole('button', {name:'圈注 原截图.png'}).click()
  await draw(page, '箭头')
  await editor(page).getByRole('button', {name:'保存圈注'}).click()
  await expect.poll(() => !!pendingSave).toBe(true)
  await page.evaluate(() => { location.hash = '/projects/1?tab=bugs&issue=62' })
  await expect(composer.getByRole('textbox')).toHaveValue('')
  await composer.getByRole('textbox').fill('第二条的草稿')
  await expect(send).toBeEnabled()
  await expect(composer.locator('.media-thumb')).toHaveCount(0)
  await page.evaluate(() => history.back())
  await expect(composer.getByRole('textbox')).toHaveValue('第一条的补充')
  await expect(send).toBeDisabled()
  await reply(pendingSave, '/app-icon-512.png')
  await expect(send).toBeEnabled()
  await expect(composer.locator('.media-thumb img')).toHaveAttribute('src', '/app-icon-512.png')
  await page.evaluate(() => history.forward())
  await expect(composer.getByRole('textbox')).toHaveValue('第二条的草稿')
  await expect(composer.locator('.media-thumb')).toHaveCount(0)
})

test('在反馈问题弹窗圈注，取消只返回原表单，保存后可单独提交带圈注的截图', async ({page}) => {
  await fixture(page, 'customer')
  await page.addInitScript(() => localStorage.setItem('customerToken', 'fixture-customer'))
  let uploads = 0
  await page.route('**/jiedan/media/upload', route => {
    uploads++
    const url = uploads === 1 ? '/app-icon-192.png' : '/app-icon-512.png'
    return route.fulfill({json:{code:200, data:{url, ext:'png'}}})
  })
  await page.goto('/#/projects/1')
  await page.getByRole('button', {name:'反馈问题', exact:true}).click()
  const form = page.getByRole('dialog', {name:'反馈问题'})
  await form.locator('input[type=file]').setInputFiles(await screenshotFile(page, '反馈截图.png'))
  const entry = form.getByRole('button', {name:'圈注 反馈截图.png'})
  await entry.click()
  await draw(page, '画圈')
  await page.keyboard.press('Escape')
  await expect(editor(page)).toBeHidden()
  await expect(form).toBeVisible()
  await expect(entry).toBeFocused()
  await entry.click()
  await draw(page, '箭头')
  await editor(page).getByRole('button', {name:'保存圈注'}).click()
  const submit = form.getByRole('button', {name:'提交反馈', exact:true})
  await expect(submit).toBeEnabled()
  const posted = page.waitForRequest(r => r.method()==='POST' && r.url().includes('/jiedan/portal/bug'))
  await submit.click()
  expect((await posted).postDataJSON().attachments).toEqual([expect.objectContaining({url:'/app-icon-512.png', annotated:true})])
})

test('多图上传中先圈注已传完的第二张，全部完成后仍按原选择顺序发送', async ({page}) => {
  await fixture(page, 'customer')
  await page.addInitScript(() => localStorage.setItem('customerToken', 'fixture-customer'))
  let slow
  const reply = (r,url) => r.fulfill({json:{code:200, data:{url,ext:'png'}}})
  await page.route('**/jiedan/media/upload', async r => {
    const request = r.request()
    const body = new Response(request.postDataBuffer(), {headers:{'Content-Type':request.headers()['content-type']}})
    const file = (await body.formData()).get('file')
    if (file.name === '第一张.png') slow = r
    else return reply(r, file.name === '第二张.png' ? '/app-icon-192.png' : '/app-icon-512.png')
  })
  await page.goto('/client/#/intake')
  const file = await screenshotFile(page, '第一张.png')
  await page.locator('form input[type=file]').setInputFiles([file,{...file,name:'第二张.png'}])
  await page.getByRole('button', {name:'圈注 第二张.png'}).click()
  await draw(page, '箭头')
  await editor(page).getByRole('button', {name:'保存圈注'}).click()
  await expect(editor(page)).toBeHidden()
  expect(slow).toBeTruthy()
  await reply(slow, '/first-image.png')
  const posted = page.waitForRequest(r => r.url().endsWith('/jiedan/order/intake') && r.method()==='POST')
  await page.locator('form.request-panel .submit').click()
  const files = (await posted).postDataJSON().attachments
  expect(files.map(i => i.url)).toEqual(['/first-image.png','/app-icon-512.png'])
  expect(files[1].annotated).toBe(true)
})
